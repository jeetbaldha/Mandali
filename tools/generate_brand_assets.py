def icon(size):
    scale = 4
    im = Image.new('RGB', (size*scale, size*scale), '#101b19')
    d = ImageDraw.Draw(im)
    k = size*scale/100
    d.ellipse([8*k,8*k,92*k,92*k], outline='#e5bc73', width=max(1,int(k*1.4)))
    for angle,color in [(0,'#e5bc73'),(math.pi/2,'#f6efdd'),(math.pi,'#e5bc73'),(3*math.pi/2,'#f6efdd')]:
        pts=[(0,-32),(11,-16),(0,-5),(-11,-16)]
        d.polygon([((50+x*math.cos(angle)-y*math.sin(angle))*k,(50+x*math.sin(angle)+y*math.cos(angle))*k) for x,y in pts],fill=color)
    d.ellipse([47*k,47*k,53*k,53*k], fill='#b44c39')
    return im.resize((size,size), Image.Resampling.LANCZOS)

