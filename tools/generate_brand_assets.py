def save(name,samples):
    with wave.open(str(assets/'audio'/f'{name}.wav'),'wb') as wav:
        wav.setnchannels(1);wav.setsampwidth(2);wav.setframerate(rate)
        wav.writeframes(b''.join(struct.pack('<h',int(max(-1,min(1,x))*24000)) for x in samples))
for name,(notes,duration) in cues.items():
    rng=random.Random(name);samples=[]
    for i in range(int(rate*duration)):
        t=i/rate;section=duration/len(notes);n=min(len(notes)-1,int(t/section));local=t-n*section
        envelope=min(1,local/.004)*math.exp(-local*14)*min(1,(duration-t)/.03)
        harmonic=math.sin(2*math.pi*notes[n]*local)+.25*math.sin(4*math.pi*notes[n]*local)
        noise=(rng.random()*2-1)*(.6 if name in ['shuffle','deal','flip'] else .025)
        samples.append((harmonic*.25+noise*.12)*envelope)
    save(name,samples)
